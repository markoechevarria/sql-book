-- Quick sanity check — expected: customers=8, orders=14, order_items=19, revenue_delivered=5737.94
SELECT (SELECT COUNT(*) FROM customers)   AS customers,
       (SELECT COUNT(*) FROM orders)      AS orders,
       (SELECT COUNT(*) FROM order_items) AS order_items,
       (SELECT ROUND(SUM(i.quantity * i.unit_price * (1 - i.discount_pct/100)), 2)
          FROM order_items i JOIN orders o USING (order_id)
         WHERE o.status = 'delivered')    AS revenue_delivered;
