-- =====================================================================
-- Acme Commerce — shared sample schema for Part II (SQL) of
-- "The Data Engineering Book".
--
-- Dialect: PostgreSQL 14+ (this file is also the reference for the
-- pathological differences noted per chapter).
--
-- Usage:
--   psql -f 00-sample-schema.sql
--   (or paste into psql / DBeaver / DataGrip / pgAdmin)
--
-- The data is deterministic so the "expected result" blocks in every
-- chapter are reproducible. The seed contains deliberate edge cases:
--   * customers with zero orders (id 8)
--   * a customer with no loyalty_tier (id 8)
--   * an inactive product (id 12)
--   * a returned and a cancelled order (1004, 1006)
--   * an order with no ship date yet (pending/paid orders)
--   * a recursive category tree (Electronics > Accessories > Cases)
--   * an employee hierarchy two levels deep under the CEO
--   * an event for a customer who never purchased (id 8)
--   * anonymous events with customer_id IS NULL (so NOT IN / IN NULL traps are reproducible)
-- =====================================================================

DROP TABLE IF EXISTS events, order_items, orders, products, categories,
                     customers, employees CASCADE;
DROP TABLE IF EXISTS value_bands, dim_product_price CASCADE;

-- ---------------------------------------------------------------------
-- Core tables
-- ---------------------------------------------------------------------
CREATE TABLE customers (
    customer_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         text        NOT NULL UNIQUE,
    full_name     text        NOT NULL,
    country_code  char(2)     NOT NULL,
    signup_ts     timestamptz NOT NULL DEFAULT now(),
    referred_by   bigint      REFERENCES customers(customer_id),
    loyalty_tier  text        CHECK (loyalty_tier IN ('bronze','silver','gold','platinum')),
    is_active     boolean     NOT NULL DEFAULT true
);

CREATE TABLE employees (
    employee_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name   text   NOT NULL,
    manager_id  bigint REFERENCES employees(employee_id),
    title       text   NOT NULL,
    hire_date   date   NOT NULL,
    salary      numeric(12,2) NOT NULL
);

CREATE TABLE categories (
    category_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text   NOT NULL,
    parent_id   bigint REFERENCES categories(category_id)
);

CREATE TABLE products (
    product_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku         text   NOT NULL UNIQUE,
    name        text   NOT NULL,
    category_id bigint NOT NULL REFERENCES categories(category_id),
    unit_price  numeric(10,2) NOT NULL CHECK (unit_price >= 0),
    cost        numeric(10,2) NOT NULL,
    is_active   boolean NOT NULL DEFAULT true,
    attributes  jsonb
);

CREATE TABLE orders (
    order_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  bigint NOT NULL REFERENCES customers(customer_id),
    status       text   NOT NULL CHECK (status IN
                   ('pending','paid','shipped','delivered','returned','cancelled')),
    ordered_at   timestamptz NOT NULL,
    shipped_at   timestamptz,
    country_code char(2) NOT NULL,
    channel      text NOT NULL DEFAULT 'web'   -- web | mobile | marketplace | store
);

CREATE TABLE order_items (
    order_item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      bigint NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
    product_id    bigint NOT NULL REFERENCES products(product_id),
    quantity      int    NOT NULL CHECK (quantity > 0),
    unit_price    numeric(10,2) NOT NULL,       -- price captured at sale time
    discount_pct  numeric(5,2)  NOT NULL DEFAULT 0
);

CREATE TABLE events (
    event_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint REFERENCES customers(customer_id),
    session_id  uuid   NOT NULL,
    event_type  text   NOT NULL,   -- page_view | add_to_cart | checkout | purchase
    occurred_at timestamptz NOT NULL,
    properties  jsonb
);

-- A small helper table used in range-join examples
CREATE TABLE value_bands (
    label text PRIMARY KEY,
    low   numeric(12,2) NOT NULL,
    high  numeric(12,2) NOT NULL
);

-- An SCD2-style dimension used in the as-of join examples
CREATE TABLE dim_product_price (
    product_id bigint NOT NULL REFERENCES products(product_id),
    valid_from date   NOT NULL,
    valid_to   date,                 -- NULL = open interval
    price      numeric(10,2) NOT NULL,
    PRIMARY KEY (product_id, valid_from)
);

-- ---------------------------------------------------------------------
-- Indexes the examples rely on
-- ---------------------------------------------------------------------
CREATE INDEX idx_orders_customer   ON orders (customer_id, ordered_at DESC);
CREATE INDEX idx_orders_status     ON orders (status, ordered_at);
CREATE INDEX idx_items_order       ON order_items (order_id);
CREATE INDEX idx_items_product     ON order_items (product_id);
CREATE INDEX idx_products_category ON products (category_id);
CREATE INDEX idx_events_customer   ON events (customer_id, occurred_at DESC);

